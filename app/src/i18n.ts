type LabelKey = keyof typeof labels.zh;

export function getLang(): Lang {
  const raw = localStorage.getItem(LANG_KEY);
  return raw === "zh" || raw === "fr" ? raw : "en";
}

export function setLang(lang: Lang) {
  localStorage.setItem(LANG_KEY, lang);
  window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: lang }));
}

export function useLang(): [Lang, (lang: Lang) => void] {
  const [lang, setCurrentLang] = useState<Lang>(() => getLang());

  useEffect(() => {
    const refresh = () => setCurrentLang(getLang());
    window.addEventListener(LANG_EVENT, refresh);
    window.addEventListener("storage", refresh);
    return () => {
      window.removeEventListener(LANG_EVENT, refresh);
      window.removeEventListener("storage", refresh);
    };
  }, []);

  return [lang, setLang];
}

export function tr(lang: Lang, key: LabelKey, params: Record<string, string | number> = {}) {
  let value: string = labels[lang][key] ?? labels.zh[key];
  for (const [name, replacement] of Object.entries(params)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}
